    # ── Appendix G — screenshots ─────────────────────────────────
    def _appendix_screenshots(self) -> list:
        s = self.state
        if not s.screenshots:
            return []
        out = ["## Appendix G — Web Screenshots", "",
               f"{len(s.screenshots)} screenshot(s) captured:", ""]
        for shot in s.screenshots:
            path = shot.get("path")
            if not path or not Path(path).exists():
                continue
            rel = Path(path).relative_to(s.output_dir) if str(path).startswith(str(s.output_dir)) else path
            out += [f"**{shot.get('url', '')}**", "", f"![{shot.get('url', 'screenshot')}]({rel})", ""]
        return out

